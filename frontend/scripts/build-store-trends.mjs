// 店舗ページ用「混みやすい曜日・時間帯」の事前集計。
// content/insights/weekly の直近数週ぶんを集約して src/data/storeTrends.generated.json に書く。
// 実行時に Supabase / fs を読まないための事前生成（ページは静的 import するだけ）。
// 使い方: cd frontend && npm run trends:build

import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildStoreTrendEntry, selectRecentWeekFiles } from "./lib/storeTrendsCore.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const storesPath = join(root, "src", "data", "stores.json");
const outPath = join(root, "src", "data", "storeTrends.generated.json");

let stores;
try {
  stores = JSON.parse(readFileSync(storesPath, "utf8"));
  if (!Array.isArray(stores)) throw new Error("stores.json is not an array");
} catch (e) {
  console.error(`cannot read stores.json: ${e instanceof Error ? e.message : String(e)}`);
  process.exit(1);
}

const entries = {};
for (const s of stores) {
  const slug = s?.slug;
  if (typeof slug !== "string" || !slug) continue;
  const dir = join(root, "content", "insights", "weekly", slug);
  if (!existsSync(dir)) continue;
  const files = selectRecentWeekFiles(readdirSync(dir));
  const usedNames = [];
  const docs = [];
  for (const f of files) {
    try {
      docs.push(JSON.parse(readFileSync(join(dir, f), "utf8")));
      usedNames.push(f);
    } catch (e) {
      console.warn(`warn: skip broken file ${slug}/${f}: ${e instanceof Error ? e.message : String(e)}`);
    }
  }
  const entry = buildStoreTrendEntry(usedNames, docs);
  if (!entry) continue;
  entries[slug] = entry;
  console.log(`${slug} weeks=${entry.weeks.length} cells=${entry.cells.length}`);
}

const slugs = Object.keys(entries);
if (slugs.length === 0) {
  console.error("no entries built");
  process.exit(1);
}

const note =
  "generated by frontend/scripts/build-store-trends.mjs from content/insights/weekly; do not edit by hand";
const lines = slugs.map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(entries[k])}`);
const text =
  `{\n  "schemaVersion": 1,\n  "note": ${JSON.stringify(note)},\n  "stores": {\n` +
  lines.join(",\n") +
  `\n  }\n}\n`;

const prev = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
if (prev === text) {
  console.log("unchanged");
} else {
  writeFileSync(outPath, text, "utf8");
  console.log("updated");
}
